/// Нормализация текста для поискового индекса и запроса (D-043).
///
/// Токенизатор FTS5 `unicode61` не приравнивает «ё» к «е» (проба P3), поэтому
/// одинаковая нормализация применяется и при записи в индекс, и при поиске.
String normalizeForSearch(String input) =>
    input.replaceAll('ё', 'е').replaceAll('Ё', 'Е').toLowerCase();
